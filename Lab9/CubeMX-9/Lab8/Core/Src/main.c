// Read the ADC value
uint32_t readADC(void)
{
	// Start the ADC conversion
	HAL_ADC_Start(&hadc1);

	// Wait for the conversion to complete
	HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY);

	// Get the converted value
	uint32_t value = HAL_ADC_GetValue(&hadc1);

	// Return the value
	return value;
}

