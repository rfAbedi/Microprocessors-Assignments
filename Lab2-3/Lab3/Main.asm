.MODEL SMALL
.STACK 64
.DATA
    ; --- IO 8285 PORTS AND CR ---
    PORTA EQU 00H ; OUT - 1ST DIGIT
    PORTB EQU 02H ; OUT - 2ND DIGIT
    PORTC EQU 04H ; IN - KEYPAD
    CNTRLREG EQU 06H
    CNTRLBYTE EQU 10001001B
    ; ---------------------

    M DB ?
    N DB ?
    KPMN DB ?
.CODE  

MAIN    PROC FAR

    MOV AX, @DATA
	MOV DS, AX

    CALL SET_CNTRLREG
    CALL SET_NUMBER_ZERO 

ENDLESS:
	JMP ENDLESS

    ; MOV AH, 4CH
    ; INT 21H
MAIN    ENDP


TRACK_KEYPAD PROC

TRACK_KEYPAD ENDP


SHOW_NUMBER PROC ; GETS DX AS PARAMETER
    MOV AL, DH
    OUT PORTA, AL
    MOV AL, DL
    OUT PORTB, AL
    RET
SHOW_NUMBER ENDP


SET_NUMBER_ZERO PROC
    MOV DX, 0000H
    CALL SHOW_NUMBER
    RET
SET_NUMBER_ZERO ENDP


SET_CNTRLREG PROC
    MOV AL, CNTRLBYTE
    MOV DX, CNTRLREG
    OUT DX, AL
    RET
SET_CNTRLREG ENDP


; DO NOT REMOVE THIS LINE:
    END MAIN